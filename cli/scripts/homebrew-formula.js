#!/usr/bin/env node
'use strict';
// Writes the Homebrew formula for the `exotel` single-file binary from the release archives' .sha256 files.
//   node scripts/homebrew-formula.js <dir with *.sha256> [--base-url <url where the archives are hosted>]
// Default base URL: the GitHub release for this version (tag cli-v<version>) on exotel/ExotelMCP.
// The formula installs the binary and its zsh/bash/fish completions; users need no Node.js.
const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const dir = path.resolve(process.argv[2] || path.join(__dirname, '..', 'dist'));
const i = process.argv.indexOf('--base-url');
const base = (i > 0 ? process.argv[i + 1] : `https://github.com/exotel/ExotelMCP/releases/download/cli-v${pkg.version}`).replace(/\/$/, '');

const sha = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.tar.gz.sha256'))) {
  const m = /^exotel-[\d.]+-(darwin|linux)-(arm64|x64)\.tar\.gz\.sha256$/.exec(f);
  if (m) sha[`${m[1]}-${m[2]}`] = fs.readFileSync(path.join(dir, f), 'utf8').split(/\s+/)[0];
}
if (!Object.keys(sha).length) {
  console.error(`homebrew-formula: no exotel-<version>-<os>-<arch>.tar.gz.sha256 files in ${dir}`);
  process.exit(1);
}

const block = (os, arch, cpu) => (sha[`${os}-${arch}`]
  ? `    on_${cpu} do
      url "${base}/exotel-${pkg.version}-${os}-${arch}.tar.gz"
      sha256 "${sha[`${os}-${arch}`]}"
    end
` : '');
const osBlock = (os, brewOs) => {
  const body = block(os, 'arm64', 'arm') + block(os, 'x64', 'intel');
  return body ? `  on_${brewOs} do\n${body}  end\n` : '';
};

const formula = `# Generated by cli/scripts/homebrew-formula.js for exotel-cli ${pkg.version}. Do not edit by hand.
class Exotel < Formula
  desc "Exotel from the terminal: phone calls, voice bots, numbers, and coding-agent setup"
  homepage "https://www.npmjs.com/package/exotel-cli"
  version "${pkg.version}"
  license "MIT"

${osBlock('darwin', 'macos')}${osBlock('linux', 'linux')}
  def install
    bin.install "exotel"
    generate_completions_from_executable(bin/"exotel", "completion")
  end

  def caveats
    <<~EOS
      Get started:
        exotel init     # log in once (Account SID, API key, API token)
        exotel call     # place a test call, step by step
    EOS
  end

  test do
    assert_equal "${pkg.version}", shell_output("#{bin}/exotel --version").strip
    assert_match "Did you mean", shell_output("#{bin}/exotel numbr list --json 2>&1", 2)
  end
end
`;
const out = path.join(dir, 'exotel.rb');
fs.writeFileSync(out, formula);
console.log(`✔ ${out} (${Object.keys(sha).join(', ')})`);
