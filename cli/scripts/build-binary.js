#!/usr/bin/env node
'use strict';
// Builds a single-file `exotel` executable (no Node.js needed by the user) with Node's built-in
// single-executable-application support. No dependencies:
//   1. embed the known option names and the agent skills (dist/generated.json),
//   2. bundle every CLI module into one CommonJS file with a tiny module registry,
//   3. `node --build-sea` turns that file plus this Node binary into dist/exotel[.exe],
//   4. macOS: ad-hoc code signature; then a self-test of the binary.
// Usage: node scripts/build-binary.js            (current OS/arch; run on each target in CI)
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const pkg = require(path.join(ROOT, 'package.json'));
const exe = process.platform === 'win32' ? 'exotel.exe' : 'exotel';
const target = `${process.platform === 'win32' ? 'windows' : process.platform}-${process.arch}`;

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });

// 1. Embedded data ------------------------------------------------------------------------------
const skillsDir = fs.existsSync(path.join(ROOT, '..', 'skills')) ? path.join(ROOT, '..', 'skills') : path.join(ROOT, 'skills');
const skills = {};
for (const d of fs.readdirSync(skillsDir, { withFileTypes: true })) {
  const f = path.join(skillsDir, d.name, 'SKILL.md');
  if (d.isDirectory() && fs.existsSync(f)) skills[d.name] = fs.readFileSync(f, 'utf8');
}
const flags = [...require(path.join(ROOT, 'lib', 'validate.js')).knownFlags()].sort();
const generated = { version: pkg.version, flags, skills };

// 2. Bundle -------------------------------------------------------------------------------------
const modules = {};
const add = (rel) => {
  const abs = path.join(ROOT, rel);
  if (rel.endsWith('.json')) {
    modules[rel] = `function (module) { module.exports = ${fs.readFileSync(abs, 'utf8').trim()}; }`;
    return;
  }
  const code = fs.readFileSync(abs, 'utf8').replace(/^#!.*\n/, '');
  modules[rel] = `function (module, exports, require, __filename, __dirname) {\n${code}\n}`;
};
add('bin/exotel.js');
for (const dir of ['lib', 'lib/commands']) {
  for (const f of fs.readdirSync(path.join(ROOT, dir))) if (f.endsWith('.js')) add(`${dir}/${f}`);
}
add('package.json');
modules['lib/generated.json'] = `function (module) { module.exports = ${JSON.stringify(generated)}; }`;

const bundle = `'use strict';
// exotel-cli ${pkg.version} single-file bundle (generated by scripts/build-binary.js; do not edit)
const __path = require('path');
const __mods = {
${Object.entries(modules).map(([id, fn]) => `${JSON.stringify(id)}: ${fn}`).join(',\n')}
};
const __cache = {};
let __main = null;
function __resolve(from, id) {
  const base = __path.posix.normalize(__path.posix.join(__path.posix.dirname(from), id));
  for (const c of [base, base + '.js', base + '.json', base + '/index.js']) if (__mods[c]) return c;
  throw new Error('exotel bundle: cannot find module ' + id + ' from ' + from);
}
function __load(id) {
  if (__cache[id]) return __cache[id].exports;
  const m = { id, exports: {} };
  __cache[id] = m;
  if (!__main) __main = m;
  const req = (x) => (x.startsWith('.') ? __load(__resolve(id, x)) : require(x));
  req.main = __main;
  __mods[id].call(m.exports, m, m.exports, req, '/exotel/' + id, '/exotel/' + __path.posix.dirname(id));
  return m.exports;
}
__load('bin/exotel.js');
`;
const bundleFile = path.join(DIST, 'exotel-bundle.cjs');
fs.writeFileSync(bundleFile, bundle);

// 3. Single executable ----------------------------------------------------------------------------
const seaConfig = path.join(DIST, 'sea-config.json');
fs.writeFileSync(seaConfig, JSON.stringify({
  main: bundleFile, output: path.join(DIST, exe), disableExperimentalSEAWarning: true, useCodeCache: false, useSnapshot: false,
}, null, 2));
execFileSync(process.execPath, ['--build-sea', seaConfig], { stdio: 'inherit' });

// 4. Sign (macOS refuses unsigned arm64 binaries) and self-test -------------------------------------
const bin = path.join(DIST, exe);
if (process.platform === 'darwin') execFileSync('codesign', ['--sign', '-', '--force', bin], { stdio: 'inherit' });
const env = { ...process.env, EXOTEL_CONFIG_DIR: fs.mkdtempSync(path.join(os.tmpdir(), 'exotel-sea-')), NODE_NO_WARNINGS: '1' };
const v = execFileSync(bin, ['--version', '--json'], { env }).toString();
if (JSON.parse(v).version !== pkg.version) throw new Error(`self-test: version mismatch: ${v}`);
const typo = (() => { try { execFileSync(bin, ['numbr', 'list', '--json'], { env, stdio: 'pipe' }); return ''; } catch (e) { return e.stdout.toString(); } })();
if (!/Did you mean/.test(typo)) throw new Error(`self-test: typo check failed: ${typo}`);
const sk = JSON.parse(execFileSync(bin, ['skill', 'list', '--json'], { env }).toString());
const n = (sk.skills || sk).length;
if (n !== Object.keys(skills).length) throw new Error(`self-test: expected ${Object.keys(skills).length} skills, got ${n}`);
fs.rmSync(env.EXOTEL_CONFIG_DIR, { recursive: true, force: true });

// Release artefact: exotel-<version>-<os>-<arch>.tar.gz (zip on Windows) + sha256
const name = `exotel-${pkg.version}-${target}`;
const archive = path.join(DIST, `${name}${process.platform === 'win32' ? '.zip' : '.tar.gz'}`);
if (process.platform === 'win32') execFileSync('powershell', ['-Command', `Compress-Archive -Path '${bin}' -DestinationPath '${archive}'`]);
else execFileSync('tar', ['-czf', archive, '-C', DIST, exe]);
const sha = require('crypto').createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(`${archive}.sha256`, `${sha}  ${path.basename(archive)}\n`);
fs.rmSync(seaConfig);
const mb = (fs.statSync(bin).size / 1048576).toFixed(0);
console.log(`✔ ${path.relative(ROOT, bin)} (${mb} MB, self-test passed: version, typo check, ${n} skills)\n✔ ${path.relative(ROOT, archive)}  sha256 ${sha}`);
